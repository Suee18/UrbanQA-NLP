"""Auto-generate a gold QA candidate set from the processed corpus.

Strategy: for every passage we already have NER-tagged, treat each typed entity
as a potential answer span. Feed (passage, span) into a pre-trained question
generation model (`valhalla/t5-base-qg-hl`) which writes a natural-language
question whose answer is that span.

Output: `data/gold_qa/gold_candidates.jsonl` — one candidate per line, in the
exact schema metrics.py reads. The user skims it, deletes garbage rows, and
renames to `gold.jsonl` to ship.

Why this is defensible: question-generation-then-human-filter is standard
practice (used in TyDi QA, CREAK, MS MARCO derivatives). Disclose the method
in your report — "candidates generated by valhalla/t5-base-qg-hl, manually
filtered for quality and grounding" — and it's evaluatable as a real gold set.

Ablation-friendly fields:
  - `question_type`     — auto-derived from answer entity label, lets you
                          slice eval results by 'who/when/where/how_many/what'
  - `gold_passage_id`   — unlocks Recall@k and MRR retrieval metrics
  - `answer_aliases`    — empty by default; you can add format variants
                          ("969 AD", "969 CE") during the cleanup pass
"""

import argparse
import json
import os
import random
import re
import yaml
from collections import defaultdict

import torch
from transformers import AutoModelForSeq2SeqLM, T5Tokenizer


# Mirrored from src/retrieval/query_processor.py — kept inline here so this
# script doesn't transitively pull in spaCy. If you change the rules in
# query_processor, mirror the change here too.
QUESTION_TYPE_PATTERNS = [
    ("how_many", re.compile(r"^\s*how\s+(many|much)\b", re.I)),
    ("how",      re.compile(r"^\s*how\b",   re.I)),
    ("what",     re.compile(r"^\s*what\b",  re.I)),
    ("who",      re.compile(r"^\s*who\b",   re.I)),
    ("when",     re.compile(r"^\s*when\b",  re.I)),
    ("where",    re.compile(r"^\s*where\b", re.I)),
    ("why",      re.compile(r"^\s*why\b",   re.I)),
    ("which",    re.compile(r"^\s*which\b", re.I)),
]
EXPECTED_ENTITY_TYPES = {
    "who":      ["PERSON", "ORG"],
    "when":     ["DATE", "TIME"],
    "where":    ["GPE", "LOC", "FAC"],
    "how_many": ["CARDINAL", "QUANTITY", "MONEY", "PERCENT"],
    "what": [], "how": [], "which": [], "why": [], "other": [],
}


def classify_question_type(question):
    for q_type, pattern in QUESTION_TYPE_PATTERNS:
        if pattern.match(question):
            return q_type
    return "other"


QG_MODEL_NAME = "valhalla/t5-base-qg-hl"

# Entity label → (question_type, expected_entity_types).
# Mirrors src/retrieval/query_processor.py so generated candidates align
# with the type-validation logic in stage 7.
LABEL_TO_QTYPE = {
    "PERSON":   ("who",      ["PERSON", "ORG"]),
    "ORG":      ("who",      ["PERSON", "ORG"]),
    "DATE":     ("when",     ["DATE", "TIME"]),
    "TIME":     ("when",     ["DATE", "TIME"]),
    "GPE":      ("where",    ["GPE", "LOC", "FAC"]),
    "LOC":      ("where",    ["GPE", "LOC", "FAC"]),
    "FAC":      ("where",    ["GPE", "LOC", "FAC"]),
    "CARDINAL": ("how_many", ["CARDINAL", "QUANTITY", "MONEY", "PERCENT"]),
    "QUANTITY": ("how_many", ["CARDINAL", "QUANTITY", "MONEY", "PERCENT"]),
    "MONEY":    ("how_many", ["CARDINAL", "QUANTITY", "MONEY", "PERCENT"]),
    "PERCENT":  ("how_many", ["CARDINAL", "QUANTITY", "MONEY", "PERCENT"]),
    "EVENT":    ("what",     []),
    "WORK_OF_ART": ("what",  []),
    "PRODUCT":  ("what",     []),
    "NORP":     ("what",     []),  # Nationalities, religions, political groups
    "LAW":      ("what",     []),
    "LANGUAGE": ("what",     []),
}

# Defaults (overridable via CLI)
DEFAULT_PER_CITY      = 10        # final candidates per city after filtering
DEFAULT_OVER_SAMPLE   = 4         # generate this many × per_city, then filter
DEFAULT_MAX_PER_PASSAGE = 2       # cap candidates from one passage to avoid bias
DEFAULT_SEED          = 42


def load_config(config_path="configs/config.yaml"):
    with open(config_path, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def load_city_passages(processed_dir, city):
    slug = city.lower().replace(" ", "_")
    path = os.path.join(processed_dir, f"{slug}_passages.json")
    if not os.path.exists(path):
        return []
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)["passages"]


# ── Entity span filtering ──────────────────────────────────────────────

def is_acceptable_span(ent_text, ent_label, city):
    """Reject spans that would produce useless questions."""
    text = ent_text.strip()
    if len(text) < 2 or len(text) > 80:
        return False
    if not re.search(r"[A-Za-z0-9]", text):
        return False
    # Skip the city name as the answer — produces circular questions.
    if text.lower() == city.lower():
        return False
    # Skip pure stopword-y tokens that NER occasionally over-tags.
    if text.lower() in {"one", "two", "three", "first", "last", "today", "now", "year", "years"}:
        return False
    if ent_label not in LABEL_TO_QTYPE:
        return False
    return True


def collect_candidate_spans(passages, city, max_per_passage):
    """Yield (passage_dict, entity_dict) tuples for every acceptable span."""
    for p in passages:
        # Some sources (very short tourism sections) may have no entities tagged.
        ents = p.get("entities", [])
        if not ents:
            continue

        # Dedupe spans by text within one passage so we don't ask the same
        # question repeatedly when an entity is mentioned more than once.
        seen_in_passage = set()
        kept_in_passage = 0
        for ent in ents:
            if kept_in_passage >= max_per_passage:
                break
            text = ent["text"].strip()
            if text.lower() in seen_in_passage:
                continue
            if not is_acceptable_span(text, ent["label"], city):
                continue
            seen_in_passage.add(text.lower())
            kept_in_passage += 1
            yield p, ent


# ── Question generation ────────────────────────────────────────────────

class QuestionGenerator:
    """Wraps valhalla/t5-base-qg-hl. The model expects the passage with
    <hl>...<hl> markers around the answer span, and emits a question."""

    def __init__(self, model_name=QG_MODEL_NAME):
        print(f"Loading question-generation model {model_name}...")
        # Use T5Tokenizer directly — transformers 5.x's AutoTokenizer
        # mis-routes valhalla's older T5 SentencePiece files through the
        # tiktoken loader and fails. Going through T5Tokenizer skips that.
        self.tokenizer = T5Tokenizer.from_pretrained(model_name)
        self.model = AutoModelForSeq2SeqLM.from_pretrained(model_name)
        self.model.eval()
        self.device = "cuda" if torch.cuda.is_available() else "cpu"
        self.model.to(self.device)

    def generate(self, passage_text, answer_start, answer_end, max_length=64):
        """Insert <hl> markers around (answer_start, answer_end) char offsets,
        then run the model. Returns the generated question (string)."""
        marked = (
            passage_text[:answer_start]
            + "<hl> " + passage_text[answer_start:answer_end] + " <hl>"
            + passage_text[answer_end:]
        )
        prompt = f"generate question: {marked} </s>"

        inputs = self.tokenizer(
            prompt, return_tensors="pt", truncation=True, max_length=512,
        ).to(self.device)

        with torch.no_grad():
            out = self.model.generate(
                **inputs,
                max_length=max_length,
                num_beams=4,
                early_stopping=True,
            )

        question = self.tokenizer.decode(out[0], skip_special_tokens=True).strip()
        # Strip "question:" prefix that some checkpoints emit.
        question = re.sub(r"^question\s*:\s*", "", question, flags=re.I).strip()
        return question


# ── Sanity filters on generated questions ─────────────────────────────

def is_acceptable_question(question, answer):
    """Reject malformed or trivial questions."""
    q = question.strip()
    if len(q) < 8 or len(q) > 200:
        return False
    if not q.endswith("?"):
        # Generation occasionally drops the ?. Add it.
        q = q.rstrip(".!") + "?"
    # The answer text leaking into the question makes it trivially answerable.
    if answer.lower().strip() in q.lower():
        return False
    return True


def normalize_question(question):
    q = question.strip()
    if not q.endswith("?"):
        q = q.rstrip(".!") + "?"
    # Capitalize first letter
    if q and q[0].islower():
        q = q[0].upper() + q[1:]
    return q


# ── Main builder loop ─────────────────────────────────────────────────

def build_for_city(city, processed_dir, qg, per_city, over_sample,
                   max_per_passage, rng):
    """Return up to `per_city` accepted candidates for one city."""
    passages = load_city_passages(processed_dir, city)
    if not passages:
        print(f"  {city}: no processed passages found")
        return []

    # Collect every acceptable (passage, entity) pair, then random-sample
    # over_sample × per_city of them. We over-sample because some will fail
    # the post-generation question filter.
    pool = list(collect_candidate_spans(passages, city, max_per_passage))
    rng.shuffle(pool)
    target = per_city * over_sample
    pool = pool[:target]

    print(f"  {city}: {len(pool)} candidate spans → generating questions...")

    accepted = []
    seen_questions = set()  # dedupe within city
    for passage, ent in pool:
        if len(accepted) >= per_city:
            break

        try:
            question = qg.generate(passage["text"], ent["start"], ent["end"])
        except Exception as e:
            continue

        if not is_acceptable_question(question, ent["text"]):
            continue
        question = normalize_question(question)
        if question.lower() in seen_questions:
            continue
        seen_questions.add(question.lower())

        # Derive question_type from the QUESTION text (not the entity label).
        # Years like 1798 are NER-tagged as CARDINAL even when they're clearly
        # answering a 'when' question — trust the question wording.
        qtype = classify_question_type(question)
        expected_types = EXPECTED_ENTITY_TYPES.get(qtype, [])

        accepted.append({
            "city":             city,
            "question":         question,
            "answer":           ent["text"].strip(),
            "answer_aliases":   [],
            "question_type":    qtype,
            "expected_entity_types": expected_types,
            "gold_passage_id":  passage["passage_id"],
            "source_passage":   passage["text"],
            "answer_label":     ent["label"],   # original NER label, kept for analysis
        })

    print(f"  {city}: {len(accepted)} accepted")
    return accepted


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--per-city", type=int, default=DEFAULT_PER_CITY,
                        help="Target accepted candidates per city")
    parser.add_argument("--over-sample", type=int, default=DEFAULT_OVER_SAMPLE,
                        help="Generate this many × per-city raw candidates per city")
    parser.add_argument("--max-per-passage", type=int, default=DEFAULT_MAX_PER_PASSAGE)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--cities", nargs="*", default=None,
                        help="Subset of cities to process; default: all in config")
    parser.add_argument("--out", type=str, default=None,
                        help="Output JSONL path; default: data/gold_qa/gold_candidates.jsonl")
    args = parser.parse_args()

    config = load_config()
    cities = args.cities or config["cities"]
    processed_dir = config["paths"]["processed_data"]
    out_path = args.out or os.path.join(config["paths"]["gold_qa"], "gold_candidates.jsonl")

    rng = random.Random(args.seed)
    qg = QuestionGenerator()

    all_candidates = []
    for city in cities:
        city_candidates = build_for_city(
            city, processed_dir, qg,
            args.per_city, args.over_sample, args.max_per_passage, rng,
        )
        all_candidates.extend(city_candidates)

    # Assign sequential ids
    for i, c in enumerate(all_candidates, start=1):
        c["id"] = f"{i:03d}"

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        for c in all_candidates:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")

    # Summary
    by_type = defaultdict(int)
    by_city = defaultdict(int)
    for c in all_candidates:
        by_type[c["question_type"]] += 1
        by_city[c["city"]] += 1

    print(f"\nWrote {len(all_candidates)} candidates → {out_path}")
    print(f"  by type: {dict(by_type)}")
    print(f"  by city: {dict(by_city)}")
    print(f"\nNext step: open {out_path}, delete bad rows, save as gold.jsonl")


if __name__ == "__main__":
    main()
